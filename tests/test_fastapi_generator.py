def _diff(expected: str, actual: str) -> str:
    return "".join(difflib.unified_diff(
        expected.splitlines(keepends=True), actual.splitlines(keepends=True),
        fromfile="golden target", tofile="generated", n=2))


def test_generated_routes_match_golden():
    generated = generate_routes(TRIG)
    target = golden_target(GOLDEN, model_hash(TRIG))
    assert generated == target, "generated route module differs from the golden target:\n" + _diff(target, generated)


def test_header_carries_the_real_model_hash():
    text = generate_routes(TRIG)
    lines = text.splitlines()
    assert lines[0] == "# Generated by the seams FastAPI generator from the chat-app model. Do not edit."
    m = re.fullmatch(r"# model-hash: (sha256:[0-9a-f]{64})", lines[1])
    assert m, lines[1]
    assert m.group(1) == model_hash(TRIG)
    assert f'MODEL_HASH = "{model_hash(TRIG)}"' in lines


def test_generation_is_deterministic():
    assert generate_routes(TRIG) == generate_routes(TRIG)
    assert extract_routes(ModelGraph.load(TRIG)) == extract_routes(ModelGraph.load(TRIG))


