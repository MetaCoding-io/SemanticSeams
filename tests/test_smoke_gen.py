@pytest.fixture
def filled(tmp_path):
    """Chapter 9 copied with an :id on its expense example, its smoke tests generated into the copy."""
    copy, _ = copy_checkpoint(CHAPTER, tmp_path, "expenses.trig", EXAMPLE, WITH_ID)
    assert main(["smoke", str(copy / "expenses.trig"), "--out", str(copy / "generated" / "smoke")]) == 0
