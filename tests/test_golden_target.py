"""The golden-target rule (D016): seams_gen.golden strips producibility markers
from a golden artifact so a generator's output can be compared byte for byte.
Synthetic lines cover the three comment syntaxes; the real goldens check that
the stripped text has no markers left and still parses.
"""

import ast
import sys
from pathlib import Path

import jinja2
import pytest
import yaml

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from test_golden_outputs import MARKER as LINT_MARKER  # noqa: E402

from seams_gen import golden_target, strip_markers  # noqa: E402
from seams_gen.golden import MARKER  # noqa: E402

GOLDEN = ROOT / "docs" / "generation" / "golden"
HASH = "sha256:" + "0123456789abcdef" * 4


def test_marker_regex_matches_the_doc_lint():
    assert MARKER.pattern == LINT_MARKER.pattern


@pytest.mark.parametrize(
    "line, expected",
    [
        ("<!doctype html>  {# [fixed] #}", "<!doctype html>"),
        ("{# page :x [graph: :x] #}", "{# page :x #}"),
        (
            "{# Generated by the seams htmx generator. Do not edit. [fixed] #}",
            "{# Generated by the seams htmx generator. Do not edit. #}",
        ),
        ('<a href="#thread"  {# [graph: :f ifml:target :thread] #}', '<a href="#thread"'),
        ("  <li>  {# [gap: GAP-07] #}", "  <li>"),
        ("{# :chat_bpmn#ev seam:publishesTo :ch [graph: :chat_bpmn#ev] #}", "{# :chat_bpmn#ev seam:publishesTo :ch #}"),
        ("<p>no marker here</p>   ", "<p>no marker here</p>   "),
    ],
    ids=["marker-only", "prose-kept", "header", "hash-in-attr", "gap", "fragment-iri", "no-marker"],
)
def test_html_lines(line, expected):
    assert strip_markers(line, ".html") == expected


@pytest.mark.parametrize("suffix", [".py", ".yaml"])
@pytest.mark.parametrize(
    "line, expected",
    [
        ("services:  # [fixed]", "services:"),
        (
            "# Generated by the seams compose generator. Do not edit.  # [fixed]",
            "# Generated by the seams compose generator. Do not edit.",
        ),
        ("# route for :x  # [graph: :x]", "# route for :x"),
        ("x = 1  # set by :x [graph: :x]", "x = 1  # set by :x"),
        ('target = "#items"  # [graph: :f ifml:swap]', 'target = "#items"'),
        ("# :chat_bpmn#ev [graph: :chat_bpmn#ev]", "# :chat_bpmn#ev"),
        ("plain: value  ", "plain: value  "),
    ],
    ids=[
        "marker-only",
        "header",
        "separate-prose-comment",
        "prose-kept",
        "hash-in-string",
        "fragment-iri",
        "no-marker",
    ],
)
def test_hash_comment_lines(line, expected, suffix):
    assert strip_markers(line, suffix) == expected


def test_blank_lines_and_trailing_newline_kept():
    text = "a:  # [fixed]\n\n  \nb:  # [fixed]\n"
    assert strip_markers(text, ".yaml") == "a:\n\n  \nb:\n"


def test_unknown_suffix_rejected():
    with pytest.raises(ValueError, match=r"\.txt"):
        strip_markers("x  # [fixed]", ".txt")


def test_marker_outside_a_comment_rejected():
    with pytest.raises(ValueError, match="trailing"):
        strip_markers("<p>[fixed]</p>", ".html")


def test_hash_substituted(tmp_path):
    golden = tmp_path / "page.html"
    golden.write_text("{# model-hash: sha256:<model-hash> [fixed] #}\n<p>  {# [fixed] #}\n")
    assert golden_target(golden, HASH) == f"{{# model-hash: {HASH} #}}\n<p>\n"
    # A bare hex digest gets the sha256: prefix.
    assert golden_target(golden, HASH[len("sha256:") :]) == f"{{# model-hash: {HASH} #}}\n<p>\n"


@pytest.mark.parametrize("name", ["chat_page.html", "chat_api.py", "compose.yaml"])
def test_real_goldens_strip_clean(name):
    path = GOLDEN / name
    target = golden_target(path, HASH)
    assert "[graph:" not in target
    assert "[fixed]" not in target
    assert "[gap:" not in target
    assert "<model-hash>" not in target
    assert HASH in target
    assert target.endswith("\n")
    # One output line per golden line: blank lines survive, nothing is joined.
    assert target.count("\n") == path.read_text().count("\n")
    if path.suffix == ".html":
        jinja2.Environment().parse(target)
    elif path.suffix == ".py":
        ast.parse(target)
    else:
        assert isinstance(yaml.safe_load(target), dict)


def test_chat_page_header_survives():
    lines = golden_target(GOLDEN / "chat_page.html", HASH).splitlines()
    assert lines[0] == "{# Generated by the seams htmx generator from the chat-app model. Do not edit. #}"
    assert lines[1] == f"{{# model-hash: {HASH} #}}"
