# ── the generated module: no domain logic, only runtime calls ─────────────


def _tree() -> ast.Module:
    return ast.parse(generate_routes(TRIG), filename="chat_api.py")


def _functions(tree):
    return [n for n in ast.walk(tree) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]


def _runtime_calls(node) -> list[str]:
    calls = [n for n in ast.walk(node) if isinstance(n, ast.Call)
             and isinstance(n.func, ast.Attribute)
             and isinstance(n.func.value, ast.Name) and n.func.value.id == "runtime"]
    return [c.func.attr for c in sorted(calls, key=lambda c: (c.lineno, c.col_offset))]


def test_generated_handlers_hold_no_branches_or_loops():
    functions = _functions(_tree())
    assert len(functions) == 4
    banned = (ast.If, ast.IfExp, ast.Match, ast.For, ast.AsyncFor, ast.While)
    found = [f"{func.name}:{n.lineno}: {type(n).__name__}"
             for func in functions for n in ast.walk(func) if isinstance(n, banned)]
    assert not found, found


def test_send_handler_validates_starts_and_renders_only():
    posts = [f for f in _functions(_tree())
             if any(isinstance(d, ast.Call) and isinstance(d.func, ast.Attribute) and d.func.attr == "post"
                    for d in f.decorator_list)]
    assert [f.name for f in posts] == ["send_message"]
    # the decorator's runtime.policy dependency is outside the body
    body_calls = [c for stmt in posts[0].body for c in _runtime_calls(stmt)]
    assert body_calls == ["validate", "start_process", "render_fragment"]
    start = next(n for n in ast.walk(posts[0]) if isinstance(n, ast.Call)
                 and isinstance(n.func, ast.Attribute) and n.func.attr == "start_process")
    assert start.args[0].value == ":send_message_process"
    assert [k.arg for k in start.keywords] == ["correlation_key"]


def test_every_runtime_attribute_is_callable_on_runtime():
    tree = _tree()
    used = {n.attr for n in ast.walk(tree) if isinstance(n, ast.Attribute)
            and isinstance(n.value, ast.Name) and n.value.id == "runtime"}
    assert used == {"policy", "validate", "start_process", "query", "subscribe", "render_fragment"}
    for attr in sorted(used | {"load"}):
        assert callable(getattr(Runtime, attr, None)), f"Runtime.{attr} is not callable"


# ── mutation: graph edits flow through to the output ──────────────────────


def _dataset() -> Dataset:
    ds = Dataset(default_union=True)
    ds.parse(str(TRIG), format="trig")
    return ds


def _seams_graph(ds):
    return ds.graph(URIRef("urn:seams:graph:seams"))


def _set_send_template(ds, template, variables):
    g = _seams_graph(ds)
    op = URIRef(CHAT + "send_message_op")
    node = g.value(op, COMM.path)
    g.remove((node, HYDRA.template, None))
    g.add((node, HYDRA.template, Literal(template)))
    for m in list(g.objects(node, HYDRA.mapping)):
        g.remove((node, HYDRA.mapping, m))
    for var in variables:
        m = BNode()
        g.add((node, HYDRA.mapping, m))
        g.add((m, HYDRA.variable, Literal(var)))
        g.add((m, HYDRA.property, URIRef(CHAT + "id")))


def _render(ds) -> str:
    routes = extract_routes(ModelGraph(TRIG, dataset=ds))
    return render_routes(routes)["chat_api.py"]


def test_send_template_drives_decorator_and_signature():
    ds = _dataset()
    _set_send_template(ds, "/conversations/{conversation}/drafts/{draft}", ["conversation", "draft"])
    out = _render(ds)
    assert '    "/conversations/{conversation}/drafts/{draft}",' in out
    assert "async def send_message(conversation: str, draft: str, request: Request) -> HTMLResponse:" in out
    assert "async def send_message(conversation: str, request: Request)" not in out
    # the GET thread route on the old template is untouched
    assert '@router.get("/conversations/{conversation}/messages", response_class=HTMLResponse)' in out
    ast.parse(out)


def test_correlation_key_must_be_a_path_variable():
    ds = _dataset()
    _set_send_template(ds, "/threads/{thread}/messages", ["thread"])
    with pytest.raises(GeneratorError) as err:
        _render(ds)
    assert err.value.subject == CHAT + "send_message_process"
    assert err.value.predicate == str(PROC.correlationKey)


def test_non_sse_channel_raises():
    ds = _dataset()
    g = _seams_graph(ds)
    ch = URIRef(CHAT + "stream_events")
    g.remove((ch, COMM.transport, None))
    g.add((ch, COMM.transport, URIRef(str(COMM) + "WebSocket")))
    with pytest.raises(GeneratorError) as err:
        _render(ds)
    assert err.value.subject == str(ch) and err.value.predicate == str(COMM.transport)


# ── negative paths through the API and the CLI ────────────────────────────


def _copy_model(tmp_path, *edits) -> Path:
    for name in PAYLOADS:
        shutil.copy(TRIG.parent / name, tmp_path / name)
    text = TRIG.read_text(encoding="utf-8")
    for old, new in edits:
        assert text.count(old) == 1, old
        text = text.replace(old, new)
    trig = tmp_path / TRIG.name
    trig.write_text(text, encoding="utf-8")
    return trig


def _cli(*args):
    return subprocess.run([sys.executable, "-m", "seams_gen", *map(str, args)],
                          cwd=ROOT, capture_output=True, text=True)


NO_PATH = ('        seam:mediaKind seam:UIFragment ;\n'
           '        comm:path [ a hydra:IriTemplate ;\n'
           '                    hydra:template "/conversations" ] .',
           '        seam:mediaKind seam:UIFragment .')
BAD_MEDIA = ('comm:requestMediaType "application/x-www-form-urlencoded"',
             'comm:requestMediaType "text/plain"')
NO_EXECUTES = ("        seam:executes :send_message_process ;\n", "")
# Without seam:executes and without the event's seam:submitsTo, no container serves (D026).
NO_SUBMITS = ("        seam:submitsTo :send_message_op ;\n", "")


@pytest.mark.parametrize("edits, subject, predicate", [
    ((NO_PATH,), CHAT + "list_conversations_op", str(COMM.path)),
    ((BAD_MEDIA,), CHAT + "send_message_op", str(COMM.requestMediaType)),
    ((NO_EXECUTES, NO_SUBMITS), None, str(SEAM.executes)),
], ids=["no-comm-path", "unknown-request-media-type", "no-serving-container"])
def test_missing_fact_fails_api_and_cli(tmp_path, edits, subject, predicate):
    trig = _copy_model(tmp_path, *edits)
    subject = subject or trig.as_uri()  # model-level errors name the model file
    with pytest.raises(GeneratorError) as err:
        generate_routes(trig)
    assert err.value.subject == subject and err.value.predicate == predicate

    out = tmp_path / "out"
    run = _cli("fastapi", trig, "--out", out)
    assert run.returncode == 2, run.stderr
    assert subject in run.stderr and predicate in run.stderr
    assert run.stdout == ""
    assert not (out / "chat_api.py").exists()


def test_unedited_copy_generates_the_same_module(tmp_path):
    trig = _copy_model(tmp_path)
    assert generate_routes(trig) == generate_routes(TRIG)


def test_cli_writes_the_route_module(tmp_path):
    out = tmp_path / "gen"
    run = _cli("fastapi", TRIG, "--out", out)
    assert run.returncode == 0, run.stderr
    written = out / "chat_api.py"
    assert run.stdout.splitlines() == [str(written)]
    assert written.read_bytes() == generate_routes(TRIG).encode("utf-8")
    assert b"\r\n" not in written.read_bytes()


# ── a process-less model: the write rule (D026) ───────────────────────────


def test_processless_form_submission_writes_instead_of_starting(tmp_path):
    from processless_model import write_model

    trig = write_model(tmp_path)
    module = extract_routes(ModelGraph.load(trig)).modules[0]
    assert module.curie == ":expense_api" and module.not_routed == ()
    text = generate_routes(trig)
    # write validates the form itself and assigns the :id a form never sends
    assert 'expense = runtime.write(":ExpenseShape", form)' in text
    assert "start_process" not in text and "runtime.validate(" not in text
    tree = ast.parse(text)
    post = next(f for f in _functions(tree) if f.name == "submit_expense")
    assert [c for stmt in post.body for c in _runtime_calls(stmt)] == ["write", "render_fragment"]
    get = next(f for f in _functions(tree) if f.name == "list_expenses")
    assert [c for stmt in get.body for c in _runtime_calls(stmt)] == ["query", "render_fragment"]
    assert callable(getattr(Runtime, "write", None))


def test_processless_model_without_submissions_raises(tmp_path):
    from processless_model import write_model

    trig = write_model(tmp_path, submits=False)
    with pytest.raises(GeneratorError) as err:
        generate_routes(trig)
    assert err.value.subject == trig.as_uri() and err.value.predicate == str(SEAM.executes)


def test_untriggered_operation_without_a_writing_form_does_not_write(tmp_path):
    from processless_model import TRIG as EXPENSE_TRIG

    trig = tmp_path / "expenses.trig"
    trig.write_text(EXPENSE_TRIG.replace("    :expense_form seam:writes :ExpenseShape .\n", ""),
                    encoding="utf-8")
    text = generate_routes(trig)
    assert "runtime.write(" not in text and "start_process" not in text
    assert 'expense = runtime.validate(":ExpenseShape", form)' in text


