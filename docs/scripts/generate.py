#!/usr/bin/env python3
"""Writes docs/generated/ from the model's own sources, so every reference page is a
view over the files CI already parses and validates, never a second copy of them:

  seam-predicates.md  ontology/seam.ttl
  vocabularies.md     ontology/{arch,ifml,proc,state,comm,deploy}.ttl
  shapes.md           ontology/shapes/seam-shapes.ttl
  queries.md          docs/queries/*.rq, with the question table in docs/queries/README.md

Sections follow the banner comments in each source file (a line of #'s, a `# Title`
line, a line of #'s), so a page reads in the same order as the file it comes from.
`.vitepress/config.ts` rewrites each page to `reference/`. Relative links in the
output point at the source files and become GitHub links at build time.

Run by `npm run build` and `npm run dev` in docs/. Needs rdflib
(`pip install -r requirements-dev.txt` at the repository root).
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from rdflib import OWL, RDF, RDFS, Graph, Namespace, URIRef

DOCS = Path(__file__).resolve().parent.parent
ROOT = DOCS.parent
OUT = DOCS / "generated"
SH = Namespace("http://www.w3.org/ns/shacl#")
SEAM = Namespace("https://w3id.org/seams/seam#")

VOCABULARIES = ["arch", "ifml", "proc", "state", "comm", "deploy"]

BANNER = re.compile(r"^#{5,}\s*$")
TITLE = re.compile(r"^#\s+(\S.*?)\s*$")
TERM = re.compile(r"^([A-Za-z][\w-]*:[\w-]+)\s+a\s")


@dataclass
class Section:
    title: str
    terms: list[str] = field(default_factory=list)


def header(source: str) -> str:
    return (
        "<!-- Generated by docs/scripts/generate.py. Do not edit; change the source file and rebuild. -->\n\n"
        f"::: info Generated page\nThis page is generated from [`{source}`](../../{source}) on every docs build, "
        "so it always matches the file CI validates.\n:::\n\n"
    )


def sections(path: Path) -> list[Section]:
    """Banner-delimited sections of a Turtle file, each with the terms defined in it, in file order."""
    lines = path.read_text(encoding="utf-8").splitlines()
    result = [Section("Overview")]
    i = 0
    while i < len(lines):
        if BANNER.match(lines[i]) and i + 1 < len(lines) and TITLE.match(lines[i + 1]):
            result.append(Section(TITLE.match(lines[i + 1]).group(1).replace("<->", "↔")))
            i += 3 if i + 2 < len(lines) and BANNER.match(lines[i + 2]) else 2
            continue
        m = TERM.match(lines[i])
        if m:
            result[-1].terms.append(m.group(1))
        i += 1
    return [s for s in result if s.terms]


def text(value) -> str:
    """Literal text as Markdown paragraphs: whitespace collapsed inside a paragraph, blank lines kept."""
    if value is None:
        return ""
    paras = re.split(r"\n\s*\n", str(value).strip())
    return "\n\n".join(escape(" ".join(p.split())) for p in paras)


def escape(s: str) -> str:
    """Escape what VitePress would read as HTML or Vue interpolation."""
    return s.replace("&", "&amp;").replace("<", "&lt;").replace("{{", "&#123;&#123;")


def cell(s: str) -> str:
    return text(s).replace("\n\n", " ").replace("|", "\\|")


def anchor(qname: str, collisions: frozenset[str] = frozenset()) -> str:
    """A stable lowercase heading id. Where a class and a predicate differ only in case
    (seam:Notation, seam:notation), the class gets a `-class` suffix."""
    base = qname.replace(":", "-").lower()
    return base + "-class" if base in collisions and qname.split(":", 1)[1][:1].isupper() else base


def collisions_of(qnames) -> frozenset[str]:
    seen, dup = set(), set()
    for qname in qnames:
        base = qname.replace(":", "-").lower()
        (dup if base in seen else seen).add(base)
    return frozenset(dup)


def load(path: Path) -> Graph:
    g = Graph()
    g.parse(path, format="turtle")
    return g


def resolve(g: Graph, qname: str) -> URIRef:
    prefix, local = qname.split(":", 1)
    return URIRef(str(dict(g.namespaces())[prefix]) + local)


def q(g: Graph, node) -> str:
    try:
        return g.qname(node)
    except Exception:
        return str(node)


def ontology(g: Graph) -> tuple[str, str]:
    for s in g.subjects(RDF.type, OWL.Ontology):
        return str(g.value(s, RDFS.label) or ""), text(g.value(s, RDFS.comment))
    return "", ""


# --------------------------------------------------------------------------- seam.ttl


def seam_predicates() -> str:
    source = "ontology/seam.ttl"
    g = load(ROOT / source)
    label, intro = ontology(g)
    out = ["# Seam predicates\n\n", header(source), f"*{escape(label)}.* {intro}\n\n"]
    out.append(
        "Each predicate is described in the order and grouping of the ontology file. "
        "Constraints on how the predicates may be used live in the [SHACL shapes](/reference/shapes), "
        "not in `rdfs:domain` or `rdfs:range`, so most predicates below state their intended "
        "source and target in their description.\n\n"
    )
    secs = sections(ROOT / source)
    clash = collisions_of(t for sec in secs for t in sec.terms)
    for sec in secs:
        out.append(f"## {escape(sec.title)}\n\n")
        individuals = []
        for qname in sec.terms:
            node = resolve(g, qname)
            types = set(g.objects(node, RDF.type))
            if types & {
                RDFS.Class, RDF.Property, OWL.Class, OWL.ObjectProperty, OWL.DatatypeProperty, OWL.AnnotationProperty
            }:
                kind = "class" if types & {RDFS.Class, OWL.Class} else "predicate"
                lbl = g.value(node, RDFS.label)
                out.append(f"### `{qname}` {{#{anchor(qname, clash)}}}\n\n")
                out.append(f"*{kind.capitalize()}{' · ' + escape(str(lbl)) if lbl else ''}.*\n\n")
                body = text(g.value(node, RDFS.comment))
                if body:
                    out.append(body + "\n\n")
                facts = []
                for pred, name in ((RDFS.domain, "Domain"), (RDFS.range, "Range")):
                    vals = [f"`{q(g, v)}`" for v in g.objects(node, pred)]
                    if vals:
                        facts.append(f"{name}: {', '.join(vals)}")
                reveal = g.value(node, SEAM.reveal)
                if reveal is not None:
                    facts.append(f"Reveal: {g.value(reveal, RDFS.label) or q(g, reveal)}")
                if facts:
                    out.append(" · ".join(facts) + "\n\n")
            else:
                individuals.append((qname, node, types))
        if individuals:
            out.append("| Value | Kind | Meaning |\n|---|---|---|\n")
            for qname, node, types in individuals:
                kinds = ", ".join(f"`{q(g, t)}`" for t in sorted(types))
                out.append(f"| `{qname}` | {kinds} | {cell(g.value(node, RDFS.label))} |\n")
            out.append("\n")
    return "".join(out)


# --------------------------------------------------------------------------- vocabularies


def vocabularies() -> str:
    out = ["# Layer vocabularies\n\n"]
    out.append(
        "<!-- Generated by docs/scripts/generate.py. Do not edit; change the source files and rebuild. -->\n\n"
        "::: info Generated page\nThis page is generated from the layer vocabularies in "
        "[`ontology/`](../../ontology/) on every docs build.\n:::\n\n"
        "Inside each layer, SemanticSeams uses a small vocabulary of its own or an existing one; "
        "the [seam predicates](/reference/seam-predicates) only name the joins between layers. "
        "BPMN and DMN have no vocabulary here at all: their native XML is the source, and only the "
        "elements that take part in a seam get an IRI.\n\n"
    )
    for name in VOCABULARIES:
        source = f"ontology/{name}.ttl"
        g = load(ROOT / source)
        label, intro = ontology(g)
        out.append(f"## {escape(label or name)} {{#{name}}}\n\n")
        out.append(f"Source: [`{source}`](../../{source}) · prefix `{name}:`\n\n")
        if intro:
            out.append(intro + "\n\n")
        for sec in sections(ROOT / source):
            if sec.title != "Overview":
                out.append(f"### {escape(sec.title)}\n\n")
            out.append("| Term | Kind | Description |\n|---|---|---|\n")
            for qname in sec.terms:
                node = resolve(g, qname)
                types = set(g.objects(node, RDF.type))
                if types & {RDFS.Class, OWL.Class}:
                    kind = "Class"
                elif types & {RDF.Property, OWL.ObjectProperty, OWL.DatatypeProperty}:
                    kind = "Property"
                else:
                    kind = ", ".join(f"`{q(g, t)}`" for t in sorted(types)) or "Term"
                parts = []
                lbl = g.value(node, RDFS.label)
                if lbl:
                    parts.append(f"**{cell(lbl)}.**")
                if g.value(node, RDFS.comment):
                    parts.append(cell(g.value(node, RDFS.comment)))
                for pred, word in ((RDFS.subClassOf, "Subclass of"), (RDFS.domain, "Domain"), (RDFS.range, "Range")):
                    vals = [f"`{q(g, v)}`" for v in g.objects(node, pred) if isinstance(v, URIRef)]
                    if vals:
                        parts.append(f"{word} {', '.join(vals)}.")
                out.append(f"| `{qname}` | {kind} | {' '.join(parts)} |\n")
            out.append("\n")
    return "".join(out)


# --------------------------------------------------------------------------- shapes


def shapes() -> str:
    source = "ontology/shapes/seam-shapes.ttl"
    g = load(ROOT / source)
    label, intro = ontology(g)
    out = ["# SHACL shapes\n\n", header(source), f"*{escape(label)}.* {intro}\n\n"]
    out.append(
        "Every example model is validated against these shapes in CI, and the viewer shows the "
        "result on every page as its model-health badge. CI also proves that the shapes reject "
        "deliberately broken seams.\n\n"
    )
    targets = ((SH.targetClass, "instances of"), (SH.targetSubjectsOf, "subjects of"),
               (SH.targetObjectsOf, "objects of"), (SH.targetNode, "the node"))
    for sec in sections(ROOT / source):
        out.append(f"## {escape(sec.title)}\n\n")
        for qname in sec.terms:
            node = resolve(g, qname)
            if (node, RDF.type, SH.NodeShape) not in g:
                continue
            out.append(f"### `{qname}` {{#{anchor(qname)}}}\n\n")
            tgt = [f"{word} `{q(g, v)}`" for pred, word in targets for v in g.objects(node, pred)]
            if tgt:
                out.append(f"Applies to {', and '.join(tgt)}.\n\n")
            rules = []
            if g.value(node, SH.message):
                rules.append(text(g.value(node, SH.message)))
            for prop in g.objects(node, SH.property):
                path = g.value(prop, SH.path)
                msg = g.value(prop, SH.message)
                bits = []
                for p, word in ((SH["class"], "class"), (SH.minCount, "at least"), (SH.maxCount, "at most"), (SH.datatype, "datatype")):
                    v = g.value(prop, p)
                    if v is not None:
                        bits.append(f"{word} `{q(g, v)}`" if isinstance(v, URIRef) else f"{word} {v}")
                where = f"`{q(g, path)}`: " if path is not None else ""
                rules.append(where + (text(msg) if msg else ", ".join(bits)))
            for sparql in g.objects(node, SH.sparql):
                msg = g.value(sparql, SH.message)
                rules.append(text(msg) if msg else "A SPARQL constraint (see the source).")
            for r in rules:
                out.append(f"- {r}\n")
            out.append("\n")
    return "".join(out)


# --------------------------------------------------------------------------- queries


def queries() -> str:
    qdir = DOCS / "queries"
    readme = (qdir / "README.md").read_text(encoding="utf-8")
    table = {}
    for row in re.finditer(r"^\|\s*`([\w.-]+\.rq)`\s*\|\s*(.+?)\s*\|\s*`?(\?\w+)`?\s*\|\s*$", readme, re.M):
        table[row.group(1)] = (row.group(2), row.group(3))
    out = ["# Cross-layer queries\n\n"]
    out.append(
        "<!-- Generated by docs/scripts/generate.py. Do not edit; change the query files and rebuild. -->\n\n"
        "::: info Generated page\nThis page is generated from the query catalog in "
        "[`docs/queries/`](../queries/) on every docs build.\n:::\n\n"
        "The questions the one graph exists to answer, as parameterised SPARQL. Each query leaves "
        "its focus node as a free variable; the viewer binds it to the element you are looking at and "
        "shows the query as a button in the inspector's *Questions* list, never as SPARQL. "
        "CI runs every query against the worked examples and asserts the exact expected rows, so a "
        "traversal cannot silently regress to zero results.\n\n"
    )
    for path in sorted(qdir.glob("*.rq")):
        src = path.read_text(encoding="utf-8").splitlines()
        comment, body, started = [], [], False
        for line in src:
            if not started and line.startswith("#"):
                comment.append(line[1:].strip())
            else:
                started = True
                body.append(line)
        question, focus = table.get(path.name, (comment[0] if comment else path.stem, ""))
        out.append(f"## {escape(question)} {{#{path.stem}}}\n\n")
        meta = f"Source: [`docs/queries/{path.name}`](../queries/{path.name})"
        if focus:
            meta += f" · focus variable `{focus}`"
        out.append(meta + "\n\n")
        if comment and comment[0].endswith("?"):
            comment = comment[1:]
        prose = comment_prose(comment)
        if prose:
            out.append(prose + "\n\n")
        out.append("```sparql\n" + "\n".join(body).strip() + "\n```\n\n")
    return "".join(out)


def comment_prose(lines: list[str]) -> str:
    """A query's header comment as Markdown: paragraphs, with `- ` lines kept as a list."""
    blocks, para = [], []
    def flush():
        if para:
            blocks.append(escape(" ".join(" ".join(para).split())))
            para.clear()
    for line in lines:
        if not line:
            flush()
        elif line.startswith("- "):
            flush()
            blocks.append("- " + escape(" ".join(line[2:].split())))
        elif blocks and blocks[-1].startswith("- ") and not para and line.startswith(" "):
            blocks[-1] += " " + escape(" ".join(line.split()))
        else:
            para.append(line)
    flush()
    out = []
    for b in blocks:
        sep = "\n" if out and b.startswith("- ") and out[-1].lstrip().startswith("- ") else "\n\n"
        out.append((sep if out else "") + b)
    return "".join(out).strip()


def main() -> None:
    OUT.mkdir(exist_ok=True)
    pages = {
        "seam-predicates.md": seam_predicates(),
        "vocabularies.md": vocabularies(),
        "shapes.md": shapes(),
        "queries.md": queries(),
    }
    for name, content in pages.items():
        # A generated page has no source file of its own under docs/, so no edit link.
        (OUT / name).write_text("---\neditLink: false\n---\n\n" + content, encoding="utf-8")
    print(f"generate.py: wrote {len(pages)} pages to {OUT.relative_to(ROOT)}/")


if __name__ == "__main__":
    main()
