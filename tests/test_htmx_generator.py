"""The htmx page generator (M004/S04/T02, D016): generating the chat page from
the IFML model reproduces the marker-stripped golden byte for byte, carries the
real model hash, is deterministic, and fails with a GeneratorError naming the
subject and predicate when a required fact is missing.
"""

import difflib
import re
import sys
from pathlib import Path

import pytest
from rdflib import RDF, Dataset, Literal, URIRef

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from seams_gen import GeneratorError, extract_page, generate_page, golden_target  # noqa: E402
from seams_gen.htmx import IFML, TEMPLATE_DIR, TEMPLATE_NAME, render_page  # noqa: E402
from seams_runtime import ModelGraph, model_hash  # noqa: E402

TRIG = ROOT / "examples" / "chat-app" / "chat-app.trig"
GOLDEN = ROOT / "docs" / "generation" / "golden" / "chat_page.html"
CHAT = "https://example.org/chat/"
SEAM = "https://w3id.org/seams/seam#"


def _diff(expected: str, actual: str) -> str:
    return "".join(difflib.unified_diff(
        expected.splitlines(keepends=True), actual.splitlines(keepends=True),
        fromfile="golden target", tofile="generated", n=2))


def test_generated_page_matches_golden():
    generated = generate_page(TRIG)
    target = golden_target(GOLDEN, model_hash(TRIG))
    assert generated == target, "generated page differs from the golden target:\n" + _diff(target, generated)


def test_header_carries_the_real_model_hash():
    lines = generate_page(TRIG).splitlines()
    assert lines[0] == "{# Generated by the seams htmx generator from the chat-app model. Do not edit. #}"
    m = re.fullmatch(r"\{# model-hash: (sha256:[0-9a-f]{64}) #\}", lines[1])
    assert m, lines[1]
    assert m.group(1) == model_hash(TRIG)


def test_generation_is_deterministic():
    assert generate_page(TRIG) == generate_page(TRIG)
    assert extract_page(ModelGraph.load(TRIG)) == extract_page(ModelGraph.load(TRIG))


def test_template_has_no_domain_literals():
    text = (TEMPLATE_DIR / TEMPLATE_NAME).read_text(encoding="utf-8").lower()
    for word in ("chat", "conversation", "message"):
        assert word not in text, f"template hard-codes {word!r}"


def test_components_follow_ifml_order():
    page = extract_page(ModelGraph.load(TRIG))
    assert [c.id for c in page.components] == ["conversation_list", "message_thread", "compose_form"]
    assert [c.order for c in page.components] == [0, 1, 2]


def test_reordering_components_reorders_blocks():
    ds = _dataset()
    g = _ifml_graph(ds)
    for comp, order in (("conversation_list", 2), ("compose_form", 0)):
        s = URIRef(CHAT + comp)
        g.remove((s, IFML.order, None))
        g.add((s, IFML.order, Literal(order)))
    out = render_page(extract_page(ModelGraph(TRIG, dataset=ds)))
    blocks = re.findall(r"\{% block (\w+) %\}", out)
    assert blocks == ["compose_form", "message_thread", "conversation_list"]


# ── negative paths: a missing or ambiguous fact names subject + predicate ──


def _dataset() -> Dataset:
    ds = Dataset(default_union=True)
    ds.parse(str(TRIG), format="trig")
    return ds


def _ifml_graph(ds):
    return ds.graph(URIRef("urn:seams:graph:model:chat_ifml"))


def _seams_graph(ds):
    return ds.graph(URIRef("urn:seams:graph:seams"))


def _remove(graph, s, p):
    assert (URIRef(s), URIRef(p), None) in graph
    graph.remove((URIRef(s), URIRef(p), None))


def _add_landmark(ds, iri):
    g = _ifml_graph(ds)
    g.add((URIRef(iri), RDF.type, IFML.ViewContainer))
    g.add((URIRef(iri), IFML.isLandmark, Literal(True)))


def _ifml(local):
    return str(IFML) + local


@pytest.mark.parametrize("mutate, subject, predicate", [
    (lambda ds: _remove(_ifml_graph(ds), CHAT + "chat_page", _ifml("isLandmark")),
     CHAT + "chat_ifml", _ifml("isLandmark")),
    (lambda ds: _remove(_seams_graph(ds), CHAT + "send_message", SEAM + "submitsTo"),
     CHAT + "send_message", SEAM + "submitsTo"),
    (lambda ds: _remove(_ifml_graph(ds), CHAT + "message_thread", _ifml("order")),
     CHAT + "message_thread", _ifml("order")),
    (lambda ds: _remove(_ifml_graph(ds), CHAT + "chat_page", _ifml("title")),
     CHAT + "chat_page", _ifml("title")),
    (lambda ds: _remove(_ifml_graph(ds), CHAT + "select_to_thread", _ifml("swap")),
     CHAT + "select_to_thread", _ifml("swap")),
    (lambda ds: _remove(_seams_graph(ds), CHAT + "message_thread_op", SEAM + "rendersComponent"),
     CHAT + "message_thread", SEAM + "rendersComponent"),
    (lambda ds: _remove(_seams_graph(ds), CHAT + "chat_ui", SEAM + "presents"),
     CHAT + "chat_ifml", SEAM + "presents"),
    (lambda ds: _seams_graph(ds).add((URIRef(CHAT + "message_thread"), URIRef(SEAM + "visibleWhen"),
                                      URIRef(CHAT + "s_bogus"))),
     CHAT + "message_thread", SEAM + "visibleWhen"),
    (lambda ds: _add_landmark(ds, CHAT + "other_page"),
     CHAT + "chat_ifml", _ifml("isLandmark")),
], ids=["no-landmark", "no-submitsTo", "no-order", "no-title", "no-swap", "no-read-op",
        "no-presenter", "two-guards", "two-landmarks"])
def test_missing_or_ambiguous_fact_raises(mutate, subject, predicate):
    ds = _dataset()
    mutate(ds)
    with pytest.raises(GeneratorError) as err:
        extract_page(ModelGraph(TRIG, dataset=ds))
    assert err.value.subject == subject
    assert err.value.predicate == predicate
    assert subject in str(err.value) and predicate in str(err.value)
