def _docker_compose_available() -> bool:
    if shutil.which("docker") is None:
        return False
    try:
        return subprocess.run(["docker", "compose", "version"], capture_output=True, timeout=30).returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


@pytest.mark.parametrize("env", ENVIRONMENTS)
def test_docker_compose_config_accepts_output(env):
    if not _docker_compose_available():
        pytest.skip("docker compose is not installed")
    with tempfile.NamedTemporaryFile(
        "w", suffix=".compose.yaml", dir=ROOT, delete=False, encoding="utf-8", newline="\n"
    ) as fh:
        fh.write(generate_compose(TRIG, env, base_dir=ROOT))
    try:
        run = subprocess.run(
            ["docker", "compose", "-f", fh.name, "--project-directory", str(ROOT), "config", "-q"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=60,
        )
        assert run.returncode == 0, run.stderr
    finally:
        Path(fh.name).unlink()


