def test_a_policy_that_does_not_admit_the_identity_is_a_skip_naming_it(filled):
    module = _module(filled / "generated" / "smoke" / "test_smoke.py")
    submit = module.SUBMIT_EXPENSE_OP
    assert submit.path == "/expenses/e-1"
    assert submit.data == (
        ("description", "Train to Leeds"),
        ("amount", "42.50"),
        ("date", "2026-10-01"),
        ("id", "e-1"),
    )
    reason = smoke_skip(submit, MANAGER)
    assert reason is not None and ":employee_submit_policy" in reason and "employee" in reason
    assert smoke_skip(submit, EMPLOYEE) is None
    assert ":employee_submit_policy" in smoke_skip(submit, Caller("http://testserver"))
    assert smoke_skip(module.LIST_EXPENSES_OP, MANAGER) is None


def test_the_generated_probes_pass_against_the_app(filled, tmp_path, monkeypatch):
    module = _module(filled / "generated" / "smoke" / "test_smoke.py")
    graph = ModelGraph(filled / "expenses.trig")
    with serve_directory(filled, tmp_path, monkeypatch) as (client, _):
        for probe in (module.SUBMIT_EXPENSE_OP, module.LIST_EXPENSES_OP, module.LIST_PAYMENTS_OP):
            check = smoke(graph, probe, EMPLOYEE, client=client)
            assert check.ok, check.message
        denied = smoke(graph, module.SUBMIT_EXPENSE_OP, MANAGER, client=client)
    assert not denied.ok
    assert "POST http://testserver/expenses/e-1 as manager" in denied.message
    assert "answered 403" in denied.message


def _run(path, **env):
    clean = {k: v for k, v in os.environ.items() if not k.startswith(("SEAMS_SMOKE_", "SEAMS_E2E"))}
    return subprocess.run(
        [sys.executable, "-m", "pytest", str(path), "-q", "-p", "no:cacheprovider", "--import-mode=importlib"],
        cwd=ROOT,
        env={**clean, **env},
        capture_output=True,
        text=True,
        timeout=300,
    )


def test_the_module_skips_without_a_base_url_and_fails_under_e2e(filled):
    path = filled / "generated" / "smoke" / "test_smoke.py"
    skipped = _run(path)
    assert skipped.returncode == 0, skipped.stdout + skipped.stderr
    assert "9 skipped" in skipped.stdout, skipped.stdout
    failed = _run(path, SEAMS_E2E="1")
    assert failed.returncode == 1, failed.stdout + failed.stderr
    assert "SEAMS_SMOKE_BASE_URL is not set" in failed.stdout


def test_the_caller_comes_from_the_environment():
    assert smoke_caller({}) is None
    assert smoke_caller({"SEAMS_SMOKE_BASE_URL": "  "}) is None
    caller = smoke_caller(
        {
            "SEAMS_SMOKE_BASE_URL": "http://localhost:8080/",
            "SEAMS_SMOKE_USER": "ann",
            "SEAMS_SMOKE_GROUPS": "employee, manager",
        }
    )
    assert caller == Caller("http://localhost:8080", "ann", ("employee", "manager"))
    assert caller.headers == {"X-Forwarded-User": "ann", "X-Forwarded-Groups": "employee,manager"}
    assert Caller("http://x").headers == {}
    assert smoke_required({"SEAMS_E2E": "1"}) and not smoke_required({})


# ── response_conforms and smoke's checks ────────────────────────────────────

VALID = {"description": "Train to Leeds", "amount": 42.5, "date": "2026-10-01", "unknown": "ignored"}
INVALID = {"description": "Refund", "amount": -5.0, "date": "2026-10-01"}


def test_response_conforms_passes_a_valid_body_and_fails_an_invalid_one(model):
    shape = EX + "ExpenseShape"
    assert response_conforms(model, shape, VALID) == (True, response_conforms(model, shape, VALID)[1])
    assert response_conforms(model, shape, [VALID, VALID])[0]
    assert response_conforms(model, shape, [])[0]
    conforms, report = response_conforms(model, shape, INVALID)
    assert not conforms and "MinInclusive" in report
    assert not response_conforms(model, shape, [VALID, INVALID])[0]
    assert not response_conforms(model, shape, {"amount": 42.5})[0]  # description and date are required
    conforms, report = response_conforms(model, shape, "not an object")
    assert not conforms and "expected a JSON object" in report


JSON_PROBE = Probe(
    iri=EX + "probe",
    method="GET",
    path="/things",
    returns=EX + "ExpenseShape",
    errors=((502, EX + "NotifyProblemShape"),),
)


def _client(status, body=None, content_type="application/json", error=None):
    def answer(request):
        if error is not None:
            raise error
        if content_type.endswith("json"):
            return httpx.Response(status, json=body, headers={"content-type": content_type})
        return httpx.Response(status, text=body or "", headers={"content-type": content_type})

    return httpx.Client(transport=httpx.MockTransport(answer))


@pytest.mark.parametrize(
    ("client", "ok", "says"),
    [
        (_client(200, VALID), True, "conforms to"),
        (_client(200, INVALID), False, "MinInclusive"),
        (_client(200, "<li>expense</li>", "text/html"), False, "not JSON"),
        (_client(404, {"detail": "no"}), False, "not 2xx or a declared error status (502)"),
        (_client(502, {"title": "down", "status": 502}, "application/problem+json"), True, "conforms to"),
        (_client(502, {"status": 502}, "application/problem+json"), False, "NotifyProblemShape"),
        (_client(0, error=httpx.ConnectError("refused")), False, "no answer: ConnectError"),
    ],
    ids=["valid", "invalid", "html-for-json", "undeclared", "declared-error", "bad-error-body", "no-answer"],
)
def test_smoke_checks_status_and_body(model, client, ok, says):
    check = smoke(model, JSON_PROBE, EMPLOYEE, client=client)
    assert check.ok is ok, check.message
    assert check.message.startswith("GET http://testserver/things as employee (groups: employee)")
    assert says in check.message


def test_a_fragment_is_checked_by_status_only(model):
    fragment = Probe(iri=EX + "probe", method="GET", path="/things", json=False, returns=EX + "ExpenseShape")
    assert smoke(model, fragment, EMPLOYEE, client=_client(200, "<li>x</li>", "text/html")).ok
    assert not smoke(model, fragment, EMPLOYEE, client=_client(500, "boom", "text/html")).ok
