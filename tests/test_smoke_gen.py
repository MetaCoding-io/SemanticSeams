"""The smoke generator (M015/S05, backlog A9): one test per operation, called on a running app.

On chapter 9 the generator writes one test per hydra:Operation with a
method and a path, by IRI, deterministically, under the model-hash header.
Chapter 9's expense example has no :id, so every operation on
/expenses/{expense} is skipped with a reason naming the variable; a copy
whose example gains an :id fills them, and there the submit operation is
skipped for a manager (its policy names the employee) and passes against the
real app for an employee. ``smoke`` itself is checked against stub answers:
a conforming JSON body passes, a non-conforming one fails with the method,
URL, status and pyshacl report, and an undeclared status, a non-JSON body or
no answer at all fail. Without SEAMS_SMOKE_BASE_URL the generated module
skips, and under SEAMS_E2E=1 it fails instead.
"""

