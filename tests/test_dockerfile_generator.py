"""The runtime image Dockerfile generator (M016/S03, ADR-0015).

Goldens in tests/golden/dockerfile/ hold sha256:<model-hash> where the model
hash goes. Error cases edit a copy of the chat app in tmp_path, beside a copy
of the root pyproject.toml and each workspace member's pyproject.toml.
"""

from __future__ import annotations

import shutil
from pathlib import Path

import pytest
from seams import load
from seams_cli import generator_inputs, load_project

from seams_gen import GeneratorError, builtin
from seams_gen.__main__ import main
from seams_gen.dockerfile import dockerfile_inputs, extract_dockerfile, generate_dockerfiles
from tests.workspace_copy import copy_workspace, workspace_members

ROOT = Path(__file__).resolve().parents[1]
GOLDEN = ROOT / "tests" / "golden" / "dockerfile"
PLACEHOLDER = "sha256:<model-hash>"
CHAT_DIR = ROOT / "examples" / "chat-app"
CHAT = CHAT_DIR / "chat-app.trig"
CHAPTER_09 = ROOT / "examples" / "expenses" / "chapter-09" / "expenses.trig"
DEPLOY = "https://w3id.org/seams/deploy#"

RUNTIME_BUILD = """
                              deploy:build [ a deploy:Build ;
                                             deploy:context "../.." ;
                                             deploy:dockerfile "examples/chat-app/generated/chat_api.Dockerfile" ] ] ;"""


@pytest.mark.parametrize(
    ("trig", "name"), [(CHAT, "chat_api.Dockerfile"), (CHAPTER_09, "expense_api.Dockerfile")], ids=["chat", "ch09"]
)
def test_dockerfile_equals_the_golden(trig, name):
    files = generate_dockerfiles(trig)
    assert list(files) == [name]
    expected = (GOLDEN / name).read_text(encoding="utf-8").replace(PLACEHOLDER, load(trig).hash)
    assert files[name] == expected


def test_generation_is_deterministic():
    assert generate_dockerfiles(CHAT) == generate_dockerfiles(CHAT)


def test_header_and_labels_name_the_model_hash_and_container():
    text = generate_dockerfiles(CHAT)["chat_api.Dockerfile"]
    model_hash = load(CHAT).hash
    lines = text.splitlines()
    assert lines[0] == "# Generated by the seams dockerfile generator from the chat-app model. Do not edit."
    assert lines[1] == f"# model-hash: {model_hash}"
    assert lines[2] == "# container: https://example.org/chat/chat_api"
    assert f'LABEL io.semanticseams.model-hash="{model_hash}" \\' in lines
    assert '      io.semanticseams.container="https://example.org/chat/chat_api"' in lines


def test_paths_are_literal_with_no_build_args():
    text = generate_dockerfiles(CHAPTER_09)["expense_api.Dockerfile"]
    assert "ARG " not in text and "${SEAMS_" not in text
    assert "COPY examples/expenses/chapter-09/generated/expense_api.py /app/expense_api.py" in text
    assert "COPY examples/expenses/chapter-09/generated/templates /app/templates" in text
    assert "COPY examples/expenses/chapter-09/seed.json /app/seed.json" in text
    assert "    SEAMS_ROUTES=/app/expense_api.py \\" in text
    assert "chat" not in text


def test_the_cli_writes_the_file(tmp_path):
    assert main(["dockerfile", str(CHAT), "--out", str(tmp_path)]) == 0
    assert [p.name for p in tmp_path.iterdir()] == ["chat_api.Dockerfile"]


def _chat_copy(tmp_path: Path, old: str, new: str, workspace: bool = True) -> Path:
    if workspace:
        copy_workspace(tmp_path)
    app = tmp_path / "examples" / "chat-app"
    shutil.copytree(CHAT_DIR, app, ignore=shutil.ignore_patterns("generated"))
    trig = app / "chat-app.trig"
    text = trig.read_text(encoding="utf-8")
    assert text.count(old) == 1, old
    trig.write_text(text.replace(old, new), encoding="utf-8")
    return trig


def test_a_serving_container_without_a_development_build_names_it_and_deploy_build(tmp_path):
    trig = _chat_copy(tmp_path, RUNTIME_BUILD, " ] ;")
    with pytest.raises(GeneratorError) as err:
        extract_dockerfile(load(trig))
    assert err.value.subject == "https://example.org/chat/chat_api"
    assert err.value.predicate == DEPLOY + "build"


def test_the_cli_exits_2_on_a_missing_build(tmp_path, capsys):
    trig = _chat_copy(tmp_path, RUNTIME_BUILD, " ] ;")
    out = tmp_path / "out"
    assert main(["dockerfile", str(trig), "--out", str(out)]) == 2
    err = capsys.readouterr().err
    assert "https://example.org/chat/chat_api" in err and DEPLOY + "build" in err
    assert not out.exists()


def test_a_model_without_a_serving_container_names_seam_executes(tmp_path):
    trig = _chat_copy(tmp_path, "        seam:executes :send_message_process ;\n", "")
    text = trig.read_text(encoding="utf-8")
    trig.write_text(text.replace("        seam:submitsTo :send_message_op ;\n", ""), encoding="utf-8")
    with pytest.raises(GeneratorError) as err:
        extract_dockerfile(load(trig))
    assert err.value.predicate == "https://w3id.org/seams/seam#executes"
    assert "found none" in str(err.value)


def test_a_build_context_outside_the_model_directory_names_deploy_context(tmp_path):
    trig = _chat_copy(
        tmp_path,
        'deploy:context "../.." ;\n                                             deploy:dockerfile "examples/chat-app/',
        'deploy:context "../../elsewhere" ;\n                                             deploy:dockerfile "examples/chat-app/',
    )
    with pytest.raises(GeneratorError) as err:
        extract_dockerfile(load(trig))
    assert err.value.subject == "https://example.org/chat/chat_api"
    assert err.value.predicate == DEPLOY + "context"


@pytest.mark.parametrize("trig", [CHAT, CHAPTER_09], ids=["chat", "ch09"])
def test_the_model_builds_the_committed_generated_dockerfile(trig):
    d = extract_dockerfile(load(trig))
    context = trig.parent / d.context
    committed = context / d.dockerfile
    assert committed.is_file()
    assert committed.read_text(encoding="utf-8") == generate_dockerfiles(trig)[committed.name]


STATED = 'deploy:dockerfile "examples/chat-app/generated/chat_api.Dockerfile"'


def test_a_stale_deploy_dockerfile_names_it(tmp_path):
    trig = _chat_copy(tmp_path, STATED, 'deploy:dockerfile "examples/chat-app/generated/old_api.Dockerfile"')
    with pytest.raises(GeneratorError) as err:
        extract_dockerfile(load(trig))
    assert err.value.subject == "https://example.org/chat/chat_api"
    assert err.value.predicate == DEPLOY + "dockerfile"
    assert "'examples/chat-app/generated/old_api.Dockerfile'" in str(err.value)
    assert "'examples/chat-app/generated/chat_api.Dockerfile'" in str(err.value)


def test_a_build_without_a_deploy_dockerfile_names_it(tmp_path):
    trig = _chat_copy(tmp_path, " ;\n                                             " + STATED, "")
    with pytest.raises(GeneratorError) as err:
        extract_dockerfile(load(trig))
    assert err.value.subject == "https://example.org/chat/chat_api"
    assert err.value.predicate == DEPLOY + "dockerfile"
    assert "states None" in str(err.value)


def test_an_equivalent_deploy_dockerfile_path_is_accepted(tmp_path):
    trig = _chat_copy(tmp_path, STATED, 'deploy:dockerfile "./examples/chat-app/generated/chat_api.Dockerfile"')
    assert extract_dockerfile(load(trig)).dockerfile == "examples/chat-app/generated/chat_api.Dockerfile"


@pytest.mark.parametrize("chapter", ["chapter-08", "chapter-09", "chapter-10"])
def test_each_expenses_build_names_the_generated_dockerfile(chapter):
    d = extract_dockerfile(load(ROOT / "examples" / "expenses" / chapter / "expenses.trig"))
    assert d.dockerfile == f"examples/expenses/{chapter}/generated/expense_api.Dockerfile"


def test_the_members_are_the_root_workspace_members_sorted():
    d = extract_dockerfile(load(CHAT))
    assert [m.path for m in d.members] == sorted(workspace_members())
    assert "seams_edit" in [m.path for m in d.members]
    by_path = {m.path: m.files for m in d.members}
    assert by_path["packages/seams"] == ("README.md", "pyproject.toml")
    assert by_path["seams_edit"] == ("pyproject.toml",)
    text = generate_dockerfiles(CHAT)["chat_api.Dockerfile"]
    assert "COPY seams_edit/pyproject.toml /app/seams_edit/" in text


def test_a_context_without_a_pyproject_names_deploy_context(tmp_path):
    trig = _chat_copy(tmp_path, STATED, STATED, workspace=False)
    with pytest.raises(GeneratorError) as err:
        extract_dockerfile(load(trig))
    assert err.value.subject == "https://example.org/chat/chat_api"
    assert err.value.predicate == DEPLOY + "context"
    assert "pyproject.toml" in str(err.value)


def test_a_missing_member_pyproject_names_it_and_deploy_context(tmp_path):
    trig = _chat_copy(tmp_path, STATED, STATED)
    (tmp_path / "seams_edit" / "pyproject.toml").unlink()
    with pytest.raises(GeneratorError) as err:
        extract_dockerfile(load(trig))
    assert err.value.predicate == DEPLOY + "context"
    assert "seams_edit/pyproject.toml" in str(err.value)


@pytest.mark.parametrize(
    "workspace",
    ['[project]\nname = "x"\n', "[tool.uv.workspace]\nmembers = []\n", "[tool.uv.workspace\n"],
    ids=["no-workspace", "no-members", "malformed"],
)
def test_a_root_pyproject_without_members_names_deploy_context(tmp_path, workspace):
    trig = _chat_copy(tmp_path, STATED, STATED)
    (tmp_path / "pyproject.toml").write_text(workspace, encoding="utf-8")
    with pytest.raises(GeneratorError) as err:
        extract_dockerfile(load(trig))
    assert err.value.predicate == DEPLOY + "context"
    assert "pyproject.toml" in str(err.value)


def test_a_globbed_member_names_it_and_deploy_context(tmp_path):
    trig = _chat_copy(tmp_path, STATED, STATED)
    (tmp_path / "pyproject.toml").write_text('[tool.uv.workspace]\nmembers = ["packages/*"]\n', encoding="utf-8")
    with pytest.raises(GeneratorError) as err:
        extract_dockerfile(load(trig))
    assert err.value.predicate == DEPLOY + "context"
    assert "'packages/*'" in str(err.value)


def test_the_inputs_are_the_workspace_pyprojects():
    """The files beyond the model extract_dockerfile reads (ADR-0016), absolute and sorted."""
    expected = sorted([ROOT / "pyproject.toml", *(ROOT / m / "pyproject.toml" for m in workspace_members())])
    assert list(dockerfile_inputs(CHAT, CHAT_DIR / "generated")) == expected
    assert builtin.dockerfile.inputs is dockerfile_inputs
    assert generator_inputs(load_project(CHAT_DIR), CHAT) == tuple(expected)


def test_the_inputs_leave_out_what_is_missing_and_never_raise(tmp_path):
    trig = _chat_copy(tmp_path, STATED, STATED, workspace=False)
    assert dockerfile_inputs(trig, tmp_path) == ()
    copy_workspace(tmp_path)
    (tmp_path / "seams_edit" / "pyproject.toml").unlink()
    found = dockerfile_inputs(trig, tmp_path)
    assert (tmp_path / "pyproject.toml").resolve() in found
    assert (tmp_path / "seams_edit" / "pyproject.toml").resolve() not in found
    no_build = _chat_copy(tmp_path / "other", RUNTIME_BUILD, " ] ;", workspace=False)
    assert dockerfile_inputs(no_build, tmp_path) == ()
