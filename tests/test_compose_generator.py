"""The docker compose generator (M004/S06/T01-T02, D016, D018; M016/S02,
ADR-0015): it writes one compose file per arch:Environment, and generating
each with base_dir at the repo root reproduces the marker-stripped golden
compose.development.yaml and compose.production.yaml byte for byte. Each file
carries the real model hash and its environment, is deterministic, holds no
domain literals in its template, bind-mounts the model read-only into the
serving container, applies the override rule and every generator rule of the
ADR's inventory, follows graph edits, and fails with a GeneratorError naming
the subject and predicate when a required fact is missing, through both the
API and the ``python -m seams_gen compose`` CLI. When docker is installed,
``docker compose config`` accepts both files.
"""

