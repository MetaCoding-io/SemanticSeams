def _diff(expected: str, actual: str) -> str:
    return "".join(
        difflib.unified_diff(
            expected.splitlines(keepends=True),
            actual.splitlines(keepends=True),
            fromfile="golden target",
            tofile="generated",
            n=2,
        )
    )


def _doc(env: str, base_dir=ROOT) -> dict:
    return yaml.safe_load(generate_compose(TRIG, env, base_dir=base_dir))


@pytest.mark.parametrize("env", ENVIRONMENTS)
def test_generated_compose_matches_golden(env):
    generated = generate_compose(TRIG, env, base_dir=ROOT)
    target = golden_target(GOLDEN / f"compose.{env}.yaml", model_hash(TRIG))
    assert generated == target, f"generated compose.{env}.yaml differs from the golden target:\n" + _diff(
        target, generated
    )


