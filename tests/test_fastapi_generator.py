"""The FastAPI route generator (M004/S05/T03, D016, D017): generating the route
module of the container that executes the process reproduces the
marker-stripped golden chat_api.py byte for byte, carries the real model hash,
is deterministic, holds no domain logic (ADR-0007 rule 1), and fails with a
GeneratorError naming the subject and predicate when a required fact is
missing.
"""

