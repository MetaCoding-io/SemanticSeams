"""The docker compose generator (M004/S06/T01, D016, D018): generating the
compose file with base_dir at the repo root reproduces the marker-stripped
golden compose.yaml byte for byte, carries the real model hash, is
deterministic, holds no domain literals in its template, bind-mounts the model
read-only into the executing container, follows graph edits, and fails with a
GeneratorError naming the subject and predicate when a required fact is
missing.
"""

import difflib
import re
import sys
from pathlib import Path

import pytest
import yaml
from rdflib import RDF, RDFS, BNode, Dataset, Literal, URIRef

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from seams_gen import GeneratorError, extract_compose, generate_compose, golden_target, render_compose  # noqa: E402
from seams_gen.compose import TEMPLATE_NAME  # noqa: E402
from seams_gen.fastapi import ARCH  # noqa: E402
from seams_gen.htmx import TEMPLATE_DIR  # noqa: E402
from seams_runtime import ModelGraph, model_hash  # noqa: E402
from seams_runtime.model import DEPLOY, SEAM  # noqa: E402

TRIG = ROOT / "examples" / "chat-app" / "chat-app.trig"
GOLDEN = ROOT / "docs" / "generation" / "golden" / "compose.yaml"
CHAT = "https://example.org/chat/"
ARCH_GRAPH = URIRef("urn:seams:graph:model:chat_architecture")
SEAMS_GRAPH = URIRef("urn:seams:graph:seams")


def _diff(expected: str, actual: str) -> str:
    return "".join(difflib.unified_diff(
        expected.splitlines(keepends=True), actual.splitlines(keepends=True),
        fromfile="golden target", tofile="generated", n=2))


def test_generated_compose_matches_golden():
    generated = generate_compose(TRIG, base_dir=ROOT)
    target = golden_target(GOLDEN, model_hash(TRIG))
    assert generated == target, "generated compose file differs from the golden target:\n" + _diff(target, generated)


def test_header_carries_the_real_model_hash():
    text = generate_compose(TRIG, base_dir=ROOT)
    lines = text.splitlines()
    assert lines[0] == "# Generated by the seams compose generator from the chat-app model. Do not edit."
    m = re.fullmatch(r"# model-hash: (sha256:[0-9a-f]{64})", lines[1])
    assert m, lines[1]
    assert m.group(1) == model_hash(TRIG)
    env = yaml.safe_load(text)["services"]["chat_api"]["environment"]
    assert env["SEAMS_MODEL_HASH"] == model_hash(TRIG)
    assert env["SEAMS_MODEL"] == "/model/chat-app.trig"


def test_generation_is_deterministic():
    assert generate_compose(TRIG, base_dir=ROOT) == generate_compose(TRIG, base_dir=ROOT)
    assert extract_compose(ModelGraph.load(TRIG), ROOT) == extract_compose(ModelGraph.load(TRIG), ROOT)


def test_base_dir_defaults_to_the_working_directory(monkeypatch):
    monkeypatch.chdir(ROOT)
    assert generate_compose(TRIG) == generate_compose(TRIG, base_dir=ROOT)


def test_template_has_no_domain_literals():
    text = (TEMPLATE_DIR / TEMPLATE_NAME).read_text(encoding="utf-8").lower()
    for word in ("chat", "message", "conversation", "postgres", "llm"):
        assert word not in text, f"template hard-codes {word!r}"


def test_structure_parses_as_compose():
    doc = yaml.safe_load(generate_compose(TRIG, base_dir=ROOT))
    assert list(doc) == ["services", "secrets", "volumes"]
    assert list(doc["services"]) == ["chat_api", "chat_ui", "llm_gateway", "message_db"]
    api = doc["services"]["chat_api"]
    assert api["volumes"] and all(v.startswith("./") and v.endswith(":ro") for v in api["volumes"])
    assert [v.split(":")[1] for v in api["volumes"]] == [
        "/model/chat-app.trig", "/model/chat_process.bpmn", "/model/routing.dmn"]
    assert api["secrets"] == ["db_url", "llm_api_key"]
    assert api["deploy"] == {"replicas": 3, "placement": {"constraints": ["node.labels.seams.node == app01"]}}
    assert all(s["external"] is True for s in doc["secrets"].values())
    assert doc["secrets"]["llm_api_key"]["name"] == "chat-prod-llm-key"
    assert doc["volumes"] == {"message_db_data": {}}
    # only the executing container gets the model
    for name, service in doc["services"].items():
        if name != "chat_api":
            assert "SEAMS_MODEL" not in service.get("environment", {})
            assert not any(":/model/" in v for v in service.get("volumes", []))


def test_bind_sources_are_relative_to_base_dir():
    doc = yaml.safe_load(generate_compose(TRIG, base_dir=ROOT / "build"))
    sources = [v.split(":")[0] for v in doc["services"]["chat_api"]["volumes"]]
    assert sources == ["./../examples/chat-app/chat-app.trig", "./../examples/chat-app/chat_process.bpmn",
                       "./../examples/chat-app/routing.dmn"]


# ── mutation: graph edits flow through to the output ──────────────────────


def _dataset() -> Dataset:
    ds = Dataset(default_union=True)
    ds.parse(str(TRIG), format="trig")
    return ds


def _render(ds) -> str:
    return render_compose(extract_compose(ModelGraph(TRIG, dataset=ds), ROOT))


def _services(ds) -> dict:
    return yaml.safe_load(_render(ds))["services"]


def _binding(ds, key):
    return next(b for b in ds.subjects(DEPLOY.key, Literal(key)))


def test_replicas_follow_the_graph():
    ds = _dataset()
    g = ds.graph(ARCH_GRAPH)
    api = URIRef(CHAT + "chat_api")
    g.remove((api, DEPLOY.replicas, None))
    g.add((api, DEPLOY.replicas, Literal(5)))
    out = _render(ds)
    assert "      replicas: 5\n" in out and "replicas: 3" not in out
    g.remove((api, DEPLOY.replicas, None))
    assert "replicas" not in _services(ds)["chat_api"]["deploy"]


def test_published_port_moves_from_expose_to_ports():
    ds = _dataset()
    gw = URIRef(CHAT + "llm_gateway")
    port = ds.value(gw, DEPLOY.port)
    ds.graph(ARCH_GRAPH).add((port, DEPLOY.publishedPort, Literal(9000)))
    service = _services(ds)["llm_gateway"]
    assert service["ports"] == ["9000:8000"]
    assert "expose" not in service


def test_placement_follows_the_node_label():
    ds = _dataset()
    g = ds.graph(ARCH_GRAPH)
    db01 = URIRef(CHAT + "db01")
    g.remove((db01, RDFS.label, None))
    g.add((db01, RDFS.label, Literal("db02")))
    service = _services(ds)["message_db"]
    assert service["deploy"]["placement"]["constraints"] == ["node.labels.seams.node == db02"]


def test_placement_follows_deployed_to():
    ds = _dataset()
    g = ds.graph(SEAMS_GRAPH)
    db = URIRef(CHAT + "message_db")
    g.remove((db, SEAM.deployedTo, None))
    g.add((db, SEAM.deployedTo, URIRef(CHAT + "app01")))
    assert _services(ds)["message_db"]["deploy"]["placement"]["constraints"] == [
        "node.labels.seams.node == app01"]
    g.remove((db, SEAM.deployedTo, None))
    assert "deploy" not in _services(ds)["message_db"]


def test_numeric_looking_value_is_quoted():
    ds = _dataset()
    b = _binding(ds, "POSTGRES_DB")
    g = ds.graph(ARCH_GRAPH)
    g.remove((b, DEPLOY.value, None))
    g.add((b, DEPLOY.value, Literal("8080")))
    out = _render(ds)
    assert '      POSTGRES_DB: "8080"\n' in out
    assert _services(ds)["message_db"]["environment"]["POSTGRES_DB"] == "8080"


# ── negative paths through the API ────────────────────────────────────────


def _raises(ds) -> GeneratorError:
    with pytest.raises(GeneratorError) as err:
        _render(ds)
    return err.value


def test_missing_artifact_names_container():
    ds = _dataset()
    db = URIRef(CHAT + "message_db")
    ds.graph(ARCH_GRAPH).remove((db, DEPLOY.artifact, None))
    err = _raises(ds)
    assert err.subject == str(db) and err.predicate == str(DEPLOY.artifact)


def test_missing_secret_name_names_container_and_key():
    ds = _dataset()
    ds.graph(ARCH_GRAPH).remove((_binding(ds, "LLM_API_KEY"), DEPLOY.secretName, None))
    err = _raises(ds)
    assert err.subject == CHAT + "chat_api" and err.predicate == str(DEPLOY.secretName)
    assert "LLM_API_KEY" in err.detail


def test_unlabelled_node_names_the_node():
    ds = _dataset()
    db01 = URIRef(CHAT + "db01")
    ds.graph(ARCH_GRAPH).remove((db01, RDFS.label, None))
    err = _raises(ds)
    assert err.subject == str(db01) and err.predicate == str(RDFS.label)


@pytest.mark.parametrize("edit", ["none", "two"])
def test_binding_needs_exactly_one_kind(edit):
    ds = _dataset()
    b = _binding(ds, "UPSTREAM_BASE_URL")
    g = ds.graph(ARCH_GRAPH)
    if edit == "none":
        g.remove((b, DEPLOY.value, None))
    else:
        g.add((b, DEPLOY.serviceOf, URIRef(CHAT + "chat_api")))
    err = _raises(ds)
    assert err.subject == CHAT + "llm_gateway" and err.predicate == str(DEPLOY.binding)
    assert "UPSTREAM_BASE_URL" in err.detail


def test_service_of_needs_a_single_port():
    ds = _dataset()
    gw = URIRef(CHAT + "llm_gateway")
    port = BNode()
    g = ds.graph(ARCH_GRAPH)
    g.add((gw, DEPLOY.port, port))
    g.add((port, RDF.type, DEPLOY.Port))
    g.add((port, DEPLOY.containerPort, Literal(9001)))
    err = _raises(ds)
    assert err.subject == str(gw) and err.predicate == str(DEPLOY.port)


@pytest.mark.parametrize("count", [0, 2])
def test_exactly_one_system(count):
    ds = _dataset()
    g = ds.graph(ARCH_GRAPH)
    system = URIRef(CHAT + "chat_system")
    if count == 0:
        g.remove((system, RDF.type, ARCH.System))
    else:
        g.add((URIRef(CHAT + "other_system"), RDF.type, ARCH.System))
    err = _raises(ds)
    assert err.subject == TRIG.resolve().as_uri() and err.predicate == str(ARCH.contains)


def test_depends_on_outside_the_system_raises():
    ds = _dataset()
    ui = URIRef(CHAT + "chat_ui")
    ds.graph(ARCH_GRAPH).add((ui, DEPLOY.dependsOn, URIRef(CHAT + "web01")))
    err = _raises(ds)
    assert err.subject == str(ui) and err.predicate == str(DEPLOY.dependsOn)
