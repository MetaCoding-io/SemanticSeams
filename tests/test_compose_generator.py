@pytest.mark.parametrize("env", ENVIRONMENTS)
def test_header_names_the_environment_and_the_real_model_hash(env):
    text = generate_compose(TRIG, env, base_dir=ROOT)
    lines = text.splitlines()
    assert lines[0] == "# Generated by the seams compose generator from the chat-app model. Do not edit."
    m = re.fullmatch(r"# model-hash: (sha256:[0-9a-f]{64})", lines[1])
    assert m, lines[1]
    assert m.group(1) == model_hash(TRIG)
    assert lines[2] == f"# environment: {CHAT}{env}"
    doc = yaml.safe_load(text)
    assert doc["name"] == "chat_system"  # the arch:System's local name, lower-cased
    env_vars = doc["services"]["chat_api"]["environment"]
    assert env_vars["SEAMS_MODEL_HASH"] == model_hash(TRIG)
    assert env_vars["SEAMS_MODEL"] == "/model/chat-app.trig"


