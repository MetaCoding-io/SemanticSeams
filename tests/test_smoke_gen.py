from seams_gen.smoke import extract_smoke, generate_smoke
from seams_runtime.model import ModelGraph
from seams_runtime.verify import (
    Caller,
    Probe,
    response_conforms,
    smoke,
    smoke_caller,
    smoke_required,
    smoke_skip,
)

CHAPTER = "chapter-09"
TRIG = chapter_dir(CHAPTER) / "expenses.trig"
EX = "https://example.org/expenses/"
EXAMPLE = ':expense_train :description "Train to Leeds" ;'
WITH_ID = ':expense_train :id "e-1" ; :description "Train to Leeds" ;'
EMPLOYEE = Caller("http://testserver", "employee", ("employee",))
MANAGER = Caller("http://testserver", "manager", ("manager",))


@pytest.fixture(scope="module")
def model():
    return ModelGraph(TRIG)


def _module(path):
    spec = importlib.util.spec_from_file_location(f"generated_smoke_{abs(hash(path))}", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


# ── the generated file ──────────────────────────────────────────────────────


def test_one_test_per_operation_with_method_and_path_by_iri():
    model = load(TRIG)
    expected = [op for op in model.operations if op.method is not None and op.path is not None]
    text = generate_smoke(TRIG)["test_smoke.py"]
    names = [line[4:].split("(")[0] for line in text.splitlines() if line.startswith("def test_")]
    assert names == [f"test_smoke_{str(op.iri).removeprefix(EX)}" for op in expected]
    assert names == sorted(names)
    assert "test_smoke_list_expenses_op" in names
    # :notify_manager_op has a path but no hydra:method: the runtime calls it, not a client
    assert "test_smoke_notify_manager_op" not in names


def test_output_is_deterministic_and_names_the_model_hash():
    first, second = generate_smoke(TRIG), generate_smoke(TRIG)
    assert first == second
    lines = first["test_smoke.py"].splitlines()
    assert lines[0] == "# Generated by the seams smoke generator from the expenses model. Do not edit."
    assert lines[1] == f"# model-hash: {load(TRIG).hash}"


def test_the_cli_writes_the_file(tmp_path):
    assert main(["smoke", str(TRIG), "--out", str(tmp_path)]) == 0
    assert (tmp_path / "test_smoke.py").read_text(encoding="utf-8") == generate_smoke(TRIG)["test_smoke.py"]


def test_a_path_variable_no_example_fills_is_a_skip_naming_it():
    probes = {p.name: p for p in extract_smoke(load(TRIG)).probes}
    details = probes["test_smoke_expense_details_op"]
    assert details.skip == '":expense_details_op: no example fills {expense}: :expense_train has no :id"'
    assert probes["test_smoke_list_expenses_op"].skip == "None"


def test_a_comment_names_the_operation_path_shape_and_policy():
    text = generate_smoke(TRIG)["test_smoke.py"]
    assert "# :submit_expense_op POST /expenses/{expense} -> :ExpenseShape (seam:UIFragment)" in text
    assert "#   governed by :employee_submit_policy (odrl:assignee :employee)" in text


