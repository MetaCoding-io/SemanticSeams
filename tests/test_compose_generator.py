def _without_sources_and_hash(text: str) -> str:
    text = re.sub(r"sha256:[0-9a-f]{64}", "sha256:HASH", text)
    return re.sub(r"(?m)^(\s+- )\.{1,2}/[^:]+(:/model/)", r"\1SRC\2", text)


