"""The edit-mode live preview (backlog I3, M019/S05).

After a save the viewer re-runs the project's generators on the edited model, in
lenient mode (D057) and in memory: ``generate_project`` only, never ``apply`` or
``write_outputs``, so the committed outputs and seams.lock are untouched. The
project is the seams.toml beside the loaded model. ``preview`` returns the panel's
facts, sorted, so the same model gives the same panel; the template only renders.
"""

from __future__ import annotations

import os
from pathlib import Path

from seams import SeamsError
from seams_cli import ProjectError, generate_project, load_project


def _relative(path: Path, root: Path) -> str:
    return Path(os.path.relpath(path, root)).as_posix()


def preview(model_path: Path, model_dir: Path) -> dict:
    """The preview of ``model_path`` generated by the project in ``model_dir``.

    ``files`` are the outputs, by path relative to the project directory;
    ``faults`` the lenient faults, as GeneratorError facts; ``lenient`` is true
    when there are any. ``error`` names why nothing was generated: no or a
    malformed seams.toml, or a model the generators cannot read.
    """
    context: dict = {"project": None, "files": [], "faults": [], "lenient": False, "error": None}
    try:
        project = load_project(model_dir)
    except ProjectError as err:
        return {**context, "error": f"no project: {err}"}
    context["project"] = _relative(project.path, model_dir.parent)
    try:
        generated = generate_project(project, model_path, lenient=True)
    except (SeamsError, OSError) as err:
        return {**context, "error": f"the generators could not read the model: {err}"}
    files = sorted(
        (
            {"path": _relative(path, project.root), "generator": out.generator, "text": out.text}
            for path, out in generated.files.items()
        ),
        key=lambda f: f["path"],
    )
    faults = [
        {"generator": f.generator, "subject": f.focus, "predicate": f.shape, "detail": f.message}
        for f in generated.faults
    ]
    return {**context, "files": files, "faults": faults, "lenient": bool(faults)}
