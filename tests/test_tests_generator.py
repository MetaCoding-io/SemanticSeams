"""The tests generator (M015/S03, ADR-0014): model scenarios and examples become pytest files.

examples/expenses/chapter-09 lists ``tests`` in its seams.toml, so
generated/tests/ holds test_scenarios.py, test_decisions.py and
test_shape_examples.py, tracked in seams.lock. These tests check that the
output is deterministic and committed, that a generated test fails when the
model's expectation is wrong (so it really checks the run, not just that it
runs), and that a malformed scenario is a GeneratorError naming the fact,
which the ADR-0014 shapes also flag (principle 5).
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys

import pytest
import rdflib
from expense_app import ROOT, chapter_dir
from seams import load
from seams_cli.generate import generate_project, write_outputs
from seams_cli.project import load_project
from test_generated_outputs_current import assert_current, committed_files, regenerate
from test_verify_vocabulary import SEAMSH, ontology, violating_shapes

from seams_gen import GeneratorError
from seams_gen.__main__ import main
from seams_gen.tests import extract_tests, generate_tests

CHAPTER = "chapter-09"
TRIG = chapter_dir(CHAPTER) / "expenses.trig"
COMMITTED = chapter_dir(CHAPTER) / "generated" / "tests"
REGENERATE = f"seams generate --project examples/expenses/{CHAPTER}"
FILES = ["test_decisions.py", "test_scenarios.py", "test_shape_examples.py"]
# The manager-approved scenario's expectation, the one text the negative case edits.
MANAGER_EXPECTS = (
    '        verify:given [ verify:field :decision ; verify:value "approved" ] ] ) ;\n'
    "        verify:expectState :s_approved .\n"
)


def copy_chapter(tmp_path, old: str, new: str):
    """Chapter 9 copied to tmp_path with ``old`` replaced by ``new`` (once) in expenses.trig."""
    copy = tmp_path / CHAPTER
    shutil.copytree(chapter_dir(CHAPTER), copy, ignore=shutil.ignore_patterns("__pycache__"))
    trig = copy / "expenses.trig"
    text = trig.read_text(encoding="utf-8")
    assert text.count(old) == 1, old
    trig.write_text(text.replace(old, new), encoding="utf-8")
    return copy


class Outcomes:
    """A pytest plugin recording each test's outcome by test name."""

    def __init__(self):
        self.by_name: dict[str, str] = {}
        self.failures: dict[str, str] = {}

    def pytest_runtest_logreport(self, report):
        if report.when == "call" or report.outcome != "passed":
            name = report.nodeid.rsplit("::", 1)[-1]
            self.by_name[name] = report.outcome
            if report.failed:
                self.failures[name] = report.longreprtext


def run_generated(path) -> tuple[int, Outcomes]:
    outcomes = Outcomes()
    code = pytest.main(
        [str(path), "-q", "-p", "no:cacheprovider", "--import-mode=importlib", "-W", "ignore"], plugins=[outcomes]
    )
    return code, outcomes


def test_output_is_deterministic_and_committed(tmp_path):
    runs = []
    for seed in ("1", "2"):
        out = tmp_path / f"seed-{seed}"
        env = {**os.environ, "PYTHONHASHSEED": seed}
        subprocess.run(
            [sys.executable, "-m", "seams_gen", "tests", str(TRIG), "--out", str(out)],
            check=True,
            cwd=ROOT,
            env=env,
            capture_output=True,
        )
        runs.append(committed_files(out))
    assert runs[0] == runs[1]
    assert sorted(runs[0]) == FILES
    assert_current(runs[0], committed_files(COMMITTED), COMMITTED, REGENERATE)
    assert_current(regenerate("tests", TRIG, tmp_path / "cli"), runs[0], COMMITTED, REGENERATE)


def test_names_and_header_come_from_the_model():
    model = load(TRIG)
    files = generate_tests(TRIG)
    for text in files.values():
        lines = text.splitlines()
        assert lines[0] == "# Generated by the seams tests generator from the expenses model. Do not edit."
        assert lines[1] == f"# model-hash: {model.hash}"
    tests = extract_tests(model)
    assert [s.name for s in tests.scenarios] == [
        "test_scenario_auto_approved",
        "test_scenario_finance_approved",
        "test_scenario_manager_approved",
    ]
    assert len(tests.decision_examples) == len(model.decision_examples) == 5
    assert [x.name for x in tests.shape_examples] == [
        "test_valid_example_ExpenseShape_expense_train",
        "test_invalid_example_ExpenseShape_expense_negative_amount",
    ]
    for s in tests.scenarios:
        assert f"def {s.name}(app):" in files["test_scenarios.py"]


def test_a_wrong_expected_state_fails_its_generated_test(tmp_path):
    copy = copy_chapter(tmp_path, MANAGER_EXPECTS, MANAGER_EXPECTS.replace(":s_approved", ":s_rejected"))
    project = load_project(copy)
    write_outputs(generate_project(project, project.model))

    code, outcomes = run_generated(copy / "generated" / "tests" / "test_scenarios.py")
    assert code == pytest.ExitCode.TESTS_FAILED
    assert outcomes.by_name == {
        "test_scenario_auto_approved": "passed",
        "test_scenario_finance_approved": "passed",
        "test_scenario_manager_approved": "failed",
    }
    # the failure names the scenario, the expectation and what the run reached
    assert (
        ":manager_approved expects :s_rejected; the entity is 'approved'"
        in outcomes.failures["test_scenario_manager_approved"]
    )


def test_a_scenario_without_a_process_is_a_generator_error_the_shapes_flag(tmp_path, capsys):
    block = ":auto_approved a verify:Scenario ;\n        verify:process :approval_process ;\n"
    copy = copy_chapter(tmp_path, block, ":auto_approved a verify:Scenario ;\n")
    trig = copy / "expenses.trig"

    with pytest.raises(GeneratorError) as err:
        generate_tests(trig)
    assert err.value.subject == "https://example.org/expenses/auto_approved"
    assert err.value.predicate == "https://w3id.org/seams/verify#process"

    assert main(["tests", str(trig), "--out", str(tmp_path / "out")]) == 2
    assert "auto_approved" in capsys.readouterr().err
    assert not (tmp_path / "out").exists()

    graph = ontology()
    for s, p, o, _ in rdflib.Dataset(default_union=True).parse(trig, format="trig").quads():
        graph.add((s, p, o))
    assert SEAMSH.ScenarioShape in violating_shapes(graph)
