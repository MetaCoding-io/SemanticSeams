def test_another_model_path_flows_into_env_and_binds(tmp_path):
    # A model at a different path and stem: SEAMS_MODEL, the hash and the bind
    # sources all follow the TriG, so the runtime loads this model, not the chat app.
    app = tmp_path / "other_app"
    app.mkdir()
    for name in PAYLOADS:
        shutil.copy(TRIG.parent / name, app / name)
    trig = app / "other.trig"
    shutil.copy(TRIG, trig)
    text = generate_compose(trig, "production", base_dir=app)
    assert text.splitlines()[0] == "# Generated by the seams compose generator from the other model. Do not edit."
    api = yaml.safe_load(text)["services"]["chat_api"]
    assert api["environment"]["SEAMS_MODEL"] == "/model/other.trig"
    assert api["environment"]["SEAMS_MODEL_HASH"] == model_hash(trig)
    assert [v.split(":")[0] for v in api["volumes"]] == ["./other.trig", "./chat_process.bpmn", "./routing.dmn"]
    assert [v.split(":")[1] for v in api["volumes"]] == [
        "/model/other.trig",
        "/model/chat_process.bpmn",
        "/model/routing.dmn",
    ]


# ── mutation: graph edits flow through to the output ──────────────────────


def _dataset() -> Dataset:
    ds = Dataset(default_union=True)
    ds.parse(str(TRIG), format="trig")
    return ds


def _render(ds, env="production") -> str:
    return render_compose(extract_compose(ModelGraph(TRIG, dataset=ds), ROOT, env))


def _services(ds, env="production") -> dict:
    return yaml.safe_load(_render(ds, env))["services"]


def _binding(ds, key, subject=None):
    """The shared binding with ``key`` (of ``subject``'s shared configuration when given)."""
    found = [b for b in ds.subjects(DEPLOY.key, Literal(key))]
    if subject is not None:
        shared = {b for cfg in ds.objects(subject, DEPLOY.configuration) for b in ds.objects(cfg, DEPLOY.binding)}
        found = [b for b in found if b in shared]
    (binding,) = found
    return binding


def _override(ds, container):
    (node,) = ds.objects(container, DEPLOY.override)
    return node


def test_replicas_follow_the_graph():
    ds = _dataset()
    g = ds.graph(ARCH_GRAPH)
    g.remove((API, DEPLOY.replicas, None))
    g.add((API, DEPLOY.replicas, Literal(5)))
    out = _render(ds)
    assert "# The model declares 5 replicas" in out and "      replicas: 1\n" in out
    g.remove((API, DEPLOY.replicas, None))
    g.add((API, DEPLOY.replicas, Literal(1)))
    out = _render(ds)
    assert "The model declares" not in out and "      replicas: 1\n" in out
    g.remove((API, DEPLOY.replicas, None))
    assert "replicas" not in _services(ds)["chat_api"]["deploy"]


